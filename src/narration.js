export function toSpoken(text) {
  // 「受水（うきんじゅ）」のようにふりがなが付いた語は、ふりがなの方を読む
  let s = text.replace(/[一-龠々]+（([ぁ-ゖァ-ヶー・]+)）/g, '$1')
  for (const [k, v] of READINGS) s = s.split(k).join(v)
  return s
    .replace(/[（）]/g, '、')
    .replace(/――/g, '、')
    .replace(/[「」『』]/g, '')
    .replace(/、+/g, '、')
    .replace(/、。/g, '。')
}

// 自然に聞こえる音声ほど高い点をつける
function score(v) {
  const n = v.name
  let s = 0
  if (/Natural|Neural|Online/i.test(n)) s += 50 // Edge のニューラル音声
  if (/Siri|Premium|プレミアム/i.test(n)) s += 45
  if (/Enhanced|拡張/i.test(n)) s += 40
  if (/Google/i.test(n)) s += 30
  if (/Nanami|Keita|O-?ren|Kyoko|Otoya|Hattori/i.test(n)) s += 10
  if (!v.localService) s += 5
  if (/Compact|eSpeak|Haruka|Ichiro|Sayaka|Ayumi/i.test(n)) s -= 20 // 古い機械的な音声
  return s
}

export function japaneseVoices() {
  const all = window.speechSynthesis?.getVoices() ?? []
  return all.filter((v) => /^ja([-_]|$)/i.test(v.lang)).sort((a, b) => score(b) - score(a))
}

// 音声の一覧は遅れて届くことがある
export function onVoicesReady(fn) {
  const synth = window.speechSynthesis
  if (!synth) return () => {}
  fn(japaneseVoices())
  const h = () => fn(japaneseVoices())
  synth.addEventListener('voiceschanged', h)
  return () => synth.removeEventListener('voiceschanged', h)
}

export function speak(text, { voiceName, onEnd } = {}) {
  const synth = window.speechSynthesis
  if (!synth) return false
  const voices = japaneseVoices()
  const voice = voices.find((v) => v.name === voiceName) ?? voices[0]
  const u = new SpeechSynthesisUtterance(toSpoken(text))
  u.lang = 'ja-JP'
  if (voice) u.voice = voice
  // ニュースの語りのように、少しゆっくり落ち着いた調子で
  u.rate = 0.94
  u.pitch = 0.96
  u.onend = onEnd
  u.onerror = onEnd
  synth.speak(u)
  return true
}
